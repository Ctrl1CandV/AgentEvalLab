#!/usr/bin/env python3
"""run.py: run your solution on generated test cases and score it with the contest's official tester.

    python3 run.py                    compile, then run cases 0-49 (seeds in tools/seeds.txt) and print every score
    python3 run.py --cases 0-9        only those cases
    python3 run.py --parallel 2       cases run at once (default 4)
    python3 run.py --seeds FILE       generate inputs for other seeds (one unsigned 64-bit integer per line) into
                                      in-FILE/ and run on those

Your solution is main.cpp (compiled with `g++ -O2 -std=gnu++20 -o main main.cpp`) or, when there is no main.cpp,
main.py (run with python3). Inputs are generated by tools/gen into in/ on first use; outputs go to out/.

A case is accepted when it finishes within the time limit, measured as CPU time (the judge allows 10% over it, plus
0.1 s), and the tester reports a score. The judge applies the same rules to the private cases, which it generates the same way from other
seeds; see prompt.md for how failed cases count.
"""
import argparse
import concurrent.futures
import json
import os
import re
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
SCORE_LINE = re.compile(r"^Score = (\d+)\s*$")


def problem():
    with open(os.path.join(HERE, "tools", "problem.json"), encoding="utf-8") as handle:
        return json.load(handle)


def compile_solution():
    if os.path.exists(os.path.join(HERE, "main.cpp")):
        result = subprocess.run(["g++", "-O2", "-std=gnu++20", "-o", "main", "main.cpp"], cwd=HERE, capture_output=True, text=True)
        if result.returncode != 0:
            print(result.stderr[-6000:])
            sys.exit("compilation failed")
        return ["./main"]
    if os.path.exists(os.path.join(HERE, "main.py")):
        return [sys.executable, "main.py"]
    sys.exit("write main.cpp or main.py first")


def inputs_for(seeds_file, directory):
    target = os.path.join(HERE, directory)
    if not os.path.isdir(target) or not os.listdir(target):
        work = os.path.join(HERE, ".gen")
        os.makedirs(work, exist_ok=True)
        result = subprocess.run([os.path.join(HERE, "tools", "gen"), os.path.abspath(seeds_file)], cwd=work, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(f"tools/gen failed: {result.stderr[-2000:]}")
        os.replace(os.path.join(work, "in"), target)
        os.rmdir(work)
    return sorted(os.path.join(target, name) for name in os.listdir(target))


def timed_run(command, stdin, stdout, stderr, wall_cap):
    """(exit status, CPU seconds of the command and its descendants, killed at the wall-clock cap)."""
    process = subprocess.Popen(command, cwd=HERE, stdin=stdin, stdout=stdout, stderr=stderr)
    deadline, killed = time.monotonic() + wall_cap, False
    while True:
        pid, status, usage = os.wait4(process.pid, os.WNOHANG)
        if pid:
            break
        if time.monotonic() > deadline:
            process.kill()
            pid, status, usage = os.wait4(process.pid, 0)
            killed = True
            break
        time.sleep(0.005)
    return os.waitstatus_to_exitcode(status), usage.ru_utime + usage.ru_stime, killed


def run_case(spec, command, path, out_dir):
    limit = spec["time_limit"]
    allowed = limit * 1.1 + 0.1
    out_path = os.path.join(out_dir, os.path.basename(path))
    guarded = ["prlimit", f"--as={spec['memory_limit']}", f"--cpu={int(allowed) + 2}", "--", *command]
    with open(path, "rb") as source, open(out_path, "wb") as sink, open(out_path + ".err", "w+b") as errors:
        if spec["problem_type"] == "reactive":
            status, seconds, killed = timed_run([os.path.join(HERE, "tools", "tester"), *guarded], source, sink, errors, limit * 3 + 2)
        else:
            status, seconds, killed = timed_run(guarded, source, sink, errors, limit * 3 + 2)
        errors.seek(0)
        stderr = errors.read().decode("utf-8", "replace")
    os.remove(out_path + ".err")
    if killed or seconds > allowed:
        return "TLE", 0, seconds, "stopped at the wall-clock cap" if killed else f"used {seconds:.2f} s of CPU time"
    if spec["problem_type"] != "reactive":
        if status != 0:
            return "RE", 0, seconds, f"exit status {status}: {stderr[-200:]}"
        stderr = subprocess.run([os.path.join(HERE, "tools", "tester"), path, out_path], capture_output=True, text=True).stderr
    if "wrong answer: " in stderr:
        return "WA", 0, seconds, stderr.split("wrong answer: ", 1)[1].strip()[:200]
    lines = [line for line in stderr.strip().splitlines() if line.strip()]
    match = SCORE_LINE.match(lines[-1]) if lines else None
    if not match:
        return ("RE" if status else "WA"), 0, seconds, stderr.strip()[-200:] or "no score"
    return "AC", int(match.group(1)), seconds, ""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cases", default=None, help="a range such as 0-9, or a list such as 3,7,11")
    parser.add_argument("--parallel", type=int, default=4)
    parser.add_argument("--seeds", default=None, help="a file of seeds to generate other inputs from")
    args = parser.parse_args()
    spec = problem()
    if args.seeds:
        directory = "in-" + os.path.splitext(os.path.basename(args.seeds))[0]
        paths = inputs_for(args.seeds, directory)
    else:
        directory = "in"
        paths = inputs_for(os.path.join(HERE, "tools", "seeds.txt"), directory)
    if args.cases:
        chosen = set()
        for part in args.cases.split(","):
            low, _, high = part.partition("-")
            chosen.update(range(int(low), int(high or low) + 1))
        paths = [path for index, path in enumerate(paths) if index in chosen]
    command = compile_solution()
    out_dir = os.path.join(HERE, "out" if directory == "in" else "out-" + directory[3:])
    os.makedirs(out_dir, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max(1, args.parallel)) as pool:
        results = list(pool.map(lambda path: run_case(spec, command, path, out_dir), paths))
    for path, (verdict, score, seconds, message) in zip(paths, results):
        print(f"{os.path.basename(path)}  {verdict:3s}  {score:>14d}  {seconds:6.2f}s  {message}")
    accepted = sum(1 for result in results if result[0] == "AC")
    total = sum(result[1] for result in results if result[0] == "AC")
    print(f"accepted {accepted}/{len(results)}, total {total}, mean {total / max(1, len(results)):.1f}, "
          f"slowest {max((result[2] for result in results), default=0):.2f}s of CPU time (limit {spec['time_limit']} s)")


if __name__ == "__main__":
    main()
