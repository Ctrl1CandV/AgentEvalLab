#!/usr/bin/env python3
"""Builds the algorithm-engineering package from ALE-Bench (python3 private/build_package.py, from the package directory).

Inputs: the ALE-Bench problem archives (SakanaAI/ALE-Bench on Hugging Face, CC BY-ND 4.0, officially provided by AtCoder
Inc.) in ~/.cache/agenteval/ale-bench/<problem>.zip, downloaded when missing, and a Rust toolchain (cargo) to compile
each problem's official tools once; the compiled tools are cached in ~/.cache/agenteval/ale-tools/<problem>/ so that a
rebuild reproduces the package byte for byte.

Statements, images and the tools' README are copied unmodified, as the licence requires; compiling the tools is a
format shift. Nothing is redistributed outside this private repository.
"""
import ast
import datetime
import hashlib
import json
import os
import pathlib
import random
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile

ROOT = pathlib.Path(".")
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.dont_write_bytecode = True
import ale  # noqa: E402
import grader  # noqa: E402

CACHE = pathlib.Path.home() / ".cache" / "agenteval"
DATASET = "https://huggingface.co/datasets/SakanaAI/ALE-Bench/resolve/main/{}.zip"
CARGO = pathlib.Path.home() / ".local" / "share" / "cargo" / "bin" / "cargo"
CARGO_ENV = {"RUSTUP_HOME": str(pathlib.Path.home() / ".local" / "share" / "rustup"), "CARGO_HOME": str(pathlib.Path.home() / ".local" / "share" / "cargo")}
# Short (four-hour) contests scored by absolute score: the length of one agent session, ranked without relative scores.
PROBLEMS = ["ahc015", "ahc026", "ahc028", "ahc032", "ahc035", "ahc039", "ahc041", "ahc042", "ahc044", "ahc046"]
PUBLIC_SEEDS = range(50)
FRESH_SEEDS = 50
# Splits (VALIDATION §3): a contest is its own structure group. The four contests calibrated by hand for 0.1.0 and named in
# its dev plan are dev; the six others are validation. Holdout comes from contests added later (TASK_LIBRARY §5).
DEV = {"ahc015", "ahc035", "ahc039", "ahc046"}


def digest(path):
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def visible(path):
    return path.is_file() and not any(part.startswith(".") or part == "__pycache__" for part in path.parts) and not path.name.endswith(".pyc")


def archive(problem):
    path = CACHE / "ale-bench" / f"{problem}.zip"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(DATASET.format(problem), path)
    return zipfile.ZipFile(path)


def tools(problem, extracted):
    """The compiled gen and tester of a problem, built once into the cache."""
    cached = CACHE / "ale-tools" / problem
    if not all((cached / name).exists() for name in ("gen", "tester")):
        source = extracted / "tools"
        subprocess.run([str(CARGO), "build", "--release", "--quiet", "--bin", "gen", "--bin", "tester"], cwd=source, check=True,
                       env={**os.environ, **CARGO_ENV})
        cached.mkdir(parents=True, exist_ok=True)
        for name in ("gen", "tester"):
            shutil.copy2(source / "target" / "release" / name, cached / name)
    return cached


def prompt(spec, standings_count, private_count):
    hours = round((datetime.datetime.fromisoformat(spec["end_at"]) - datetime.datetime.fromisoformat(spec["start_at"])).total_seconds() / 3600)
    interaction = ("**Reactive**: your program talks with the judge through standard input and output, as the statement describes; "
                   "flush your output after each turn.") if spec["problem_type"] == "reactive" else "**Batch**: read the input, print the output."
    failures = ("Each accepted case counts; a case that fails scores 0." if spec["id"] in ale.ALLOW_SCORE_NON_AC_PRIVATE else
                "As in the contest, a single case that is not accepted (wrong answer, runtime error or time limit exceeded) makes the "
                "whole submission score 0.")
    return (f"## {spec['id'].upper()}: {spec['title']}\n\n"
            f"The official statement is `public/statement.md`, unmodified, with its images in `public/images/`. The contest ran for "
            f"{hours} hours on {spec['start_at'][:10]}; {standings_count} contestants are ranked in its final standings.\n\n"
            f"- {interaction}\n"
            f"- Time limit: {spec['time_limit']:g} s per case. Memory limit: {spec['memory_limit'] // (1024 * 1024)} MiB.\n"
            f"- Judged on the contest's {private_count} private cases, generated by the same tool from other seeds. {failures}\n")


def main():
    if (ROOT / "items").exists():
        shutil.rmtree(ROOT / "items")
    if (HERE / "problems").exists():
        shutil.rmtree(HERE / "problems")
    requirements, items = {}, []
    anchors = json.loads((HERE / "anchors.json").read_text(encoding="utf-8"))
    for problem in PROBLEMS:
        with tempfile.TemporaryDirectory() as temporary:
            zipped = archive(problem)
            zipped.extractall(temporary)
            extracted = pathlib.Path(temporary) / problem
            built = tools(problem, extracted)
            private = HERE / "problems" / problem
            (private / "tools").mkdir(parents=True)
            for name in ("data.json", "standings_scores.csv", "performance.csv"):
                shutil.copy(extracted / name, private / name)
            data = json.loads((extracted / "data.json").read_text(encoding="utf-8"))
            seeds = ast.literal_eval(data["seeds"]) if isinstance(data["seeds"], str) else data["seeds"]
            (private / "private_seeds.txt").write_text("".join(f"{seed}\n" for seed in seeds["private"]), encoding="utf-8")
            # Fresh seeds of our own (grader 2.1.0): generalisation, reported apart and never ranked against the humans.
            fresh = random.Random(f"ae-fresh:{problem}")
            (private / "fresh_seeds.txt").write_text("".join(f"{fresh.getrandbits(63)}\n" for _ in range(FRESH_SEEDS)), encoding="utf-8")
            for name in ("gen", "tester"):
                shutil.copy2(built / name, private / "tools" / name)
            spec = ale.load_problem(private)
            public = ROOT / "items" / problem / "public"
            (public / "tools").mkdir(parents=True)
            shutil.copy(extracted / "statement_en.md", public / "statement.md")
            if (extracted / "images").is_dir():
                shutil.copytree(extracted / "images", public / "images")
            shutil.copy(extracted / "tools" / "README.md", public / "tools" / "README.md")
            for name in ("gen", "tester"):
                shutil.copy2(built / name, public / "tools" / name)
            (public / "tools" / "seeds.txt").write_text("".join(f"{seed}\n" for seed in PUBLIC_SEEDS), encoding="utf-8")
            (public / "tools" / "problem.json").write_text(json.dumps({key: spec[key] for key in ("problem_type", "time_limit", "memory_limit")}, sort_keys=True) + "\n", encoding="utf-8")
            shutil.copy2(HERE / "run.py", public / "run.py")
            standings = ale.load_table(private / "standings_scores.csv", "score")
            (ROOT / "items" / problem / "prompt.md").write_text(prompt(spec, standings[-1][0] - 1, len(seeds["private"])), encoding="utf-8")
        requirement = grader.requirement(problem)
        requirements[requirement] = {"id": requirement, "critical": True, "introducedAt": f"{grader.TASK_ID} {grader.TASK_VERSION}",
                                     "checkIds": [f"{problem}-{name}" for name in grader.check_names()]}
        files = sorted(str(path.relative_to(ROOT)) for path in (ROOT / "items" / problem).rglob("*") if visible(path))
        spec = ale.load_problem(HERE / "problems" / problem)
        items.append({"id": problem, "level": "short-contest", "files": [{"path": path, "sha256": digest(path)} for path in files],
                      "activeRequirementIds": [requirement], "split": "dev" if problem in DEV else "validation", "structure": f"contest:{problem}",
                      "provenance": {"source": f"ALE-Bench, AtCoder Heuristic Contest {problem[3:]} ({spec['title']}), official private seeds",
                                     "published": spec["start_at"][:10], "license": "CC BY-ND 4.0 (ALE-Bench data, AtCoder Inc.)", "exposure": "public"},
                      "anchors": {"performance": {name: anchors[problem][name] for name in ("naive", "median-contestant", "winner")},
                                  "freshTotal": {"naive": anchors[problem]["freshNaive"], "greedy": anchors[problem]["freshGreedy"]}}})
    trusted = ["calibration.md", "card.md", "rubric.md"] + sorted(str(path.relative_to(ROOT)) for path in (ROOT / "private").rglob("*") if visible(path))
    manifest = {
        "schemaVersion": 2, "id": grader.TASK_ID, "version": grader.TASK_VERSION, "familyId": "ae-algorithm-engineering",
        "capability": "engineering", "usage": "development",
        "source": {"kind": "open-source", "references": [
            "ALE-Bench: problems, official tools, seeds, standings and performance tables (huggingface.co/datasets/SakanaAI/ALE-Bench), from the AtCoder Heuristic Contest",
            "ALE-Bench code (github.com/SakanaAI/ALE-Bench): judging and ranking rules adapted in private/ale.py",
            "Imajuku et al., ALE-Bench: A Benchmark for Long-Horizon Objective-Driven Algorithm Engineering, NeurIPS 2025 Datasets and Benchmarks"]},
        "license": {"taskText": "instruction.md, prompts, run.py and the grader are project-authored.", "thirdPartyContent": [
            "Problem statements, images, tool sources (compiled here), seeds, standings and performance tables: ALE-Bench dataset, CC BY-ND 4.0, officially provided by AtCoder Inc.; used unmodified, not redistributed",
            "Judging and ranking logic adapted from the ALE-Bench code, Apache License 2.0"]},
        "entryPoint": {"instruction": "instruction.md"},
        "files": {"public": [{"path": "instruction.md", "sha256": digest("instruction.md")}], "trusted": [{"path": path, "sha256": digest(path)} for path in trusted]},
        "requirements": list(requirements.values()),
        "items": items, "toolProfiles": ["workspace-augmented"],
        "tier": "frontier", "capabilities": ["engineering"], "card": "card.md",
        "scoreModel": {
            "primary": {"kind": "metric", "metric": "performance"},
            "groups": [{"id": "accepted", "weight": 1, "critical": True, "rule": "all", "checkIds": [f"{problem}-accepted" for problem in PROBLEMS]},
                       {"id": "performance", "weight": 1, "critical": False, "rule": "metric", "checkIds": [], "metric": "performance"}],
            "metrics": [{"id": "performance", "unit": "AtCoder performance", "direction": "higher",
                         "anchors": {"version": "1", "points": [{"name": "naive", "maps": 0}, {"name": "median-contestant", "maps": 0.5}, {"name": "winner", "maps": 1}]}},
                        {"id": "total", "unit": "contest score", "direction": "higher"},
                        {"id": "performanceRank", "unit": "rank among contestants", "direction": "lower"},
                        {"id": "freshTotal", "unit": "contest score on 50 fresh seeds", "direction": "higher",
                         "anchors": {"version": "1", "points": [{"name": "naive", "maps": 0}, {"name": "greedy", "maps": 1}]}}],
        },
        "grader": {"id": "ae-ale-judge", "version": grader.GRADER_VERSION, "entryPoint": "private/grader.py", "executable": "python3",
                   "args": ["{entryPoint}", "--request", "{request}", "--result", "{result}"]},
        "environment": {"runtime": "Python 3.13 and g++ 11 (C++20)", "dependencies": "Python standard library, g++, prlimit and timeout; no network", "network": False,
                        "runtimeCheck": {"executable": "python3", "args": ["--version"], "expectedSubstring": "Python 3.13."}},
    }
    (ROOT / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
