"""Hidden tests for the ledger item: each fixture is an event list and the full expected output, written by hand.

Fixtures are grouped into checks, one per rule area. A check passes when every fixture in it produces exactly the
expected output.
"""


def ev(identifier, kind, **fields):
    return {"id": identifier, "type": kind, **fields}


def acct(currency, balance, available, frozen=False):
    return {"currency": currency, "balance": balance, "available": available, "frozen": frozen}


def results(*rows):
    """(id, outcome) pairs; outcome is "ok", "dup" or an error code."""
    return [{"id": identifier, "status": "ok" if outcome == "ok" else "duplicate" if outcome == "dup" else "rejected",
             "error": None if outcome in ("ok", "dup") else outcome} for identifier, outcome in rows]


def expected(accounts, *rows):
    return {"accounts": accounts, "results": results(*rows)}


