#!/usr/bin/env python3
"""Regenerate self-contained negative implementations from ref_impl_a.py.

The grader copies only the candidate script into an isolated directory, so a
mutant must not import sibling modules; otherwise it fails on import and never
exercises the defect it is meant to calibrate. Each mutant below is the full
reference source plus one targeted change.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MAIN_GUARD = 'if __name__ == "__main__":\n    sys.exit(main())\n'
HEADER = "# Generated by make_mutants.py from ref_impl_a.py; edit the generator, not this file.\n"

MUTATIONS = {
    # Ignores every failure and always reports success.
    "bad_impl_always_exit0.py": '''
if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        pass
    sys.exit(0)
''',
    # Touches the database file even in dry-run mode.
    "bad_impl_dryrun_writes.py": '''
if __name__ == "__main__":
    if "--db" in sys.argv:
        db = sys.argv[sys.argv.index("--db") + 1]
        if os.path.dirname(db):
            os.makedirs(os.path.dirname(db), exist_ok=True)
        sqlite3.connect(db).close()
    sys.exit(main())
''',
    # Plain INSERT instead of a primary-key upsert, so repeated apply fails.
    "bad_impl_insert_only.py": '''
def write_db(db_path, schema, names, pk, parsed_records):
    con = sqlite3.connect(db_path)
    coldefs = []
    for c in schema["columns"]:
        d = f"{c['name']} {TYPE_MAP[c['type']]}"
        if c["name"] == pk:
            d += " PRIMARY KEY"
        if c.get("unique") and c["name"] != pk:
            d += " UNIQUE"
        coldefs.append(d)
    con.execute(f"CREATE TABLE IF NOT EXISTS records ({', '.join(coldefs)})")
    ph = ",".join("?" * len(names))
    con.executemany(f"INSERT INTO records ({','.join(names)}) VALUES ({ph})",
                    [tuple(r[n] for n in names) for r in parsed_records])
    con.commit()
    con.close()


if __name__ == "__main__":
    sys.exit(main())
''',
}


def main():
    with open(os.path.join(HERE, "ref_impl_a.py"), encoding="utf-8") as handle:
        reference = handle.read()
    if not reference.endswith(MAIN_GUARD):
        raise SystemExit("ref_impl_a.py no longer ends with the expected main guard")
    body = reference[: -len(MAIN_GUARD)].rstrip("\n") + "\n\n"
    shebang, rest = body.split("\n", 1)
    for name, mutation in MUTATIONS.items():
        with open(os.path.join(HERE, name), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(shebang + "\n" + HEADER + rest + mutation.lstrip("\n"))
        print("wrote " + name)


if __name__ == "__main__":
    main()
